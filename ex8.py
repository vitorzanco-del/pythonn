# aqui lê o número que o usuário digita e converte para inteiro
numero = int(input("Digite um número inteiro: "))
 
#  aqui é o zero e números maiores que zero são positivos
if numero >= 0:
    # aqui é a saída: do número positivo
    print("Positivo")

else:
    # aqui é a saída: do número negativo
    print("Negativo")