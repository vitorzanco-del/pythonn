# Aqui é para o usuario escrever a temperatura em Celsius
# o input() sempre devolve texto,
celsius = float(input("Digite a temperatura em °C: "))

# aqui é a conversão de Celsius para Fahrenheit, e aqui onde fica o calculo para dar a resposta
fahrenheit = celsius * 1.8 + 32

# aqui vai dizer o resultado  
print(fahrenheit, "°F")